// Re-source worklist for bike prices. Reads src/data/bikes.json, prints Markdown. Changes no data.
// Usage: node scripts/price-audit.mjs [--out file.md] [--check-urls [--limit N]] [--stale-days 90] [--outlier 0.4]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const argv = process.argv.slice(2);
const flag = (n) => argv.includes(n);
const opt = (n, d) => (argv.includes(n) ? argv[argv.indexOf(n) + 1] : d);
const STALE = +opt("--stale-days", 90), OUTLIER = +opt("--outlier", 0.4), CONC = 0.5;
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const bikes = JSON.parse(readFileSync(join(root, "src/data/bikes.json"), "utf8"));
const now = new Date();

const host = (u) => { try { return new URL(u).hostname.replace(/^www\./, ""); } catch { return "(invalid url)"; } };
const median = (a) => { const s = [...a].sort((x, y) => x - y), m = s.length >> 1; return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2; };
const ageDays = (asOf) => { const t = Date.parse(`${asOf}-01`); return Number.isNaN(t) ? null : Math.floor((now - t) / 864e5); };

const share = {};
for (const b of bikes) share[host(b.priceSource)] = (share[host(b.priceSource)] ?? 0) + 1;
const byCat = {};
for (const b of bikes) (byCat[b.category] ??= []).push(b.priceBDT);
const med = Object.fromEntries(Object.entries(byCat).map(([c, p]) => [c, median(p)]));

// Optional link check: HEAD, fall back to GET; 8 s timeout; 4 at a time. Network failure is reported, never thrown.
async function probe(url) {
  const go = async (method) => {
    const ac = new AbortController(), t = setTimeout(() => ac.abort(), 8000);
    try { return (await fetch(url, { method, redirect: "follow", signal: ac.signal, headers: { "user-agent": "suggest-bike-price-audit/1 (link check)" } })).status; }
    finally { clearTimeout(t); }
  };
  try {
    let s = await go("HEAD");
    if (s === 403 || s === 405 || s === 501) s = await go("GET");
    return s >= 400 ? `HTTP ${s}` : "ok";
  } catch (e) { return `error: ${e.cause?.code ?? e.name}`; }
}
const urlResult = {};
let urlNote = "";
if (flag("--check-urls")) {
  const limit = +opt("--limit", 10);
  const urls = [...new Set(bikes.map((b) => b.priceSource))].slice(0, limit);
  const queue = [...urls];
  await Promise.all(Array.from({ length: 4 }, async () => { for (let u; (u = queue.shift()); ) urlResult[u] = await probe(u); }));
  const bad = Object.values(urlResult).filter((r) => r !== "ok");
  urlNote = `Checked ${urls.length} of ${new Set(bikes.map((b) => b.priceSource)).size} unique priceSource URLs (--limit ${limit}); ${bad.length} not ok.` +
    (bad.length === urls.length ? " Every probe failed: the network may be unavailable, so treat this as inconclusive." : "");
}

const rows = bikes.map((b) => {
  const age = ageDays(b.priceAsOf), d = host(b.priceSource), m = med[b.category];
  const dev = (b.priceBDT - m) / m;
  const other = (b.sources ?? []).filter((s) => host(s) !== d).length;
  const flags = [];
  if (age == null) flags.push("bad-date");
  else if (age > STALE) flags.push("stale");
  if (share[d] / bikes.length > CONC) flags.push("single-domain");
  if (Math.abs(dev) > OUTLIER) flags.push("outlier");
  if (urlResult[b.priceSource] && urlResult[b.priceSource] !== "ok") flags.push("dead-link");
  return { id: b.id, cat: b.category, status: b.status, asOf: b.priceAsOf, age, d, dev, other, flags, url: b.priceSource, price: b.priceBDT };
});
const score = (r) => r.flags.filter((f) => f !== "single-domain").length * 10 + r.flags.length + (r.age ?? 0) / 1000;
rows.sort((a, b) => score(b) - score(a) || a.id.localeCompare(b.id));

const count = (f) => rows.filter((r) => r.flags.includes(f)).length;
const out = [];
out.push("# Price re-sourcing worklist", "",
  `Generated by \`npm run audit:prices\` on ${now.toISOString().slice(0, 10)} from \`src/data/bikes.json\` (${bikes.length} bikes). Do not edit by hand; no data was changed.`, "",
  "## Summary", "",
  `- Stale (priceAsOf older than ${STALE} days): **${count("stale")}**`,
  `- Single-domain concentration (domain supplies over ${CONC * 100}% of bikes): **${count("single-domain")}**. ${Object.entries(share).sort((a, b) => b[1] - a[1]).map(([h, n]) => `${h} ${n}`).join(", ")}`,
  `- Outlier (price more than ${OUTLIER * 100}% from its category median): **${count("outlier")}**. Used-only classics are priced on the used market, so check these first as category mismatches, not just wrong prices.`,
  `- Bikes with no independent corroboration (no \`sources\` entry on another domain): **${rows.filter((r) => r.other === 0).length}**`,
  ...(urlNote ? [`- Link check: ${urlNote}`] : ["- Link check: not run (use `--check-urls`)."]),
  "", "Priority order: bikes with stale/outlier/dead-link flags first. Fix = find the current price on the official distributor page or a dated distributor price list, then update `priceBDT`, `priceSource`, `priceAsOf`.", "",
  "## Worklist", "",
  "| Bike id | Cat | Status | Price (BDT) | priceAsOf | Age (d) | Source domain | vs cat. median | Other-domain refs | Flags |",
  "|---|---|---|---:|---|---:|---|---:|---:|---|");
for (const r of rows)
  out.push(`| ${r.id} | ${r.cat} | ${r.status} | ${r.price.toLocaleString("en-US")} | ${r.asOf} | ${r.age ?? "?"} | ${r.d} | ${r.dev >= 0 ? "+" : ""}${Math.round(r.dev * 100)}% | ${r.other} | ${r.flags.join(", ") || "-"} |`);
if (Object.keys(urlResult).length) {
  out.push("", "## Link check results", "", "| URL | Result |", "|---|---|");
  for (const [u, r] of Object.entries(urlResult)) out.push(`| ${u} | ${r} |`);
}
const md = out.join("\n") + "\n";
if (opt("--out")) { writeFileSync(opt("--out"), md); console.error(`wrote ${opt("--out")}`); } else process.stdout.write(md);
